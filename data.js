(function build() {
  const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const SEASON_CODES = ["sp", "su", "au", "wi"];
  window.DISHES = MAINS.map(line => {
    const [name, source, tags] = line.split(" | ").map(s => s.trim());
    const t = (tags || "").split(/\s+/).filter(Boolean);
    const b = t.find(x => x.startsWith("b:"));
    return {
      id: slug(name),
      name,
      source: source || "",
      bean: b ? b.slice(2) : null,
      seasons: t.filter(x => SEASON_CODES.includes(x)),
      protein: t.includes("meat") ? "meat" : t.includes("fish") ? "fish" : "veg",
      dinner: t.includes("dinner")
    };
  });
  window.EXTRAS = EXTRAS.map(line => {
    const [name, source, kind, seasons] = line.split(" | ").map(s => s.trim());
    return {
      id: "x-" + slug(name),
      name,
      source: source || "",
      kind,
      seasons: (seasons || "").split(/\s+/).filter(Boolean)
    };
  });
})();
